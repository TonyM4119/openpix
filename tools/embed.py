# Embed web assets into a C header. index.html is gzipped.
import gzip,sys,os
out=sys.argv[1]; files=sys.argv[2:]
with open(out,'w') as f:
    f.write('// generated by tools/embed.py\n#pragma once\n#include <stdint.h>\n')
    for p in files:
        data=open(p,'rb').read()
        name=os.path.basename(p).replace('.','_').replace('-','_')
        if p.endswith('.html'):
            data=gzip.compress(data,9,mtime=0); name+='_gz'
        f.write('static const uint8_t web_%s[%d] = {\n'%(name,len(data)))
        for i in range(0,len(data),24): f.write(','.join(str(b) for b in data[i:i+24])+',\n')
        f.write('};\n')
        print(name,len(data))
